function resolveConversationalContext(rawQuery, conversationHistory = []) {
  const norm = normalizeArabic(rawQuery);
  const followUpRegex = new RegExp(
    `${AR_START}(?:منه|بتاعه|بتاعته|عنه|ليه|ارشه ازاي|استخدمه ازاي|طب|طيب|وكام|العبوات|عبواته|مادته|تركيزه|جرعته|معدله)${AR_END}`
  );
  const isFollowUp = followUpRegex.test(norm) && norm.split(/\s+/).length <= 10;

  const mentionsProductNow = PRODUCT_KEYWORDS.some((p) => norm.includes(p.key));
  if (!isFollowUp || mentionsProductNow || !conversationHistory.length) {
    return { enrichedQuery: rawQuery, carriedTopic: null };
  }

  const recentText = normalizeArabic(
    conversationHistory
      .slice(-4)
      .map((m) => m.content || '')
      .join(' ')
  );

  for (const prod of PRODUCT_KEYWORDS) {
    if (recentText.includes(prod.key)) {
      return {
        enrichedQuery: `${rawQuery} (${prod.canonical})`,
        carriedTopic: prod.canonical,
      };
    }
  }

  const pestTopics = ['الحفار', 'الندوه المبكره', 'العنكبوت الاحمر', 'النيماتودا', 'الذبابه البيضاء', 'البياض الدقيقي'];
  for (const pest of pestTopics) {
    if (recentText.includes(normalizeArabic(pest))) {
      return {
        enrichedQuery: `${rawQuery} (${pest})`,
        carriedTopic: pest,
      };
    }
  }

  return { enrichedQuery: rawQuery, carriedTopic: null };
}

